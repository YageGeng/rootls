    use std::{fs, sync::Arc, time::Instant};

    /// Recovers a vanished JPEG from its alternate PNG and exports it with the matching format.
    #[test]
    #[ignore = "requires the macOS pasteboard service"]
    fn private_pasteboard_keeps_alternate_image_for_a_vanished_file() {
        use crate::plugins::clipboard::content::{Group, Kind};

        autoreleasepool(|_| {
            let board = NSPasteboard::pasteboardWithUniqueName();
            let dir = tempfile::tempdir().unwrap();
            let path = dir.path().join("temporary.jpg");
            let png = include_bytes!("../../../../../../assets/icons/rtools-22.png");
            let url = Url::from_file_path(&path).unwrap();
            let item = NSPasteboardItem::new();
            assert!(
                item.setString_forType(
                    &NSString::from_str(url.as_str()),
                    &NSString::from_str(FILE)
                )
            );
            assert!(
                item.setData_forType(&NSData::with_bytes(png), &NSString::from_str("public.png"))
            );
            board.clearContents();
            assert!(board.writeObjects(&NSArray::from_retained_slice(&[
                ProtocolObject::from_retained(item)
            ])));
            let mut inputs = read(&board).unwrap().unwrap();
            assert_eq!(inputs.len(), 1);
            inputs.push(Input::Text("note".into()));
            let group = Group::try_from(inputs).unwrap();
            let member = &group.parts[0];
            assert_eq!(member.kind, Kind::Image);
            assert_eq!(member.uri, url.as_str());
            assert_eq!(member.bytes, png);
            let history = History::new(dir.path().join("history"));
            history
                .save(group, 0, &Arc::new(std::sync::atomic::AtomicU64::new(0)))
                .unwrap();
            let id = history.search("temporary.jpg", true).unwrap()[0].id;
            let prepared = history.prepare(id, Selection::All, None).unwrap();
            let Payload::Files(files) = prepared.payload else {
                panic!("expected a file group")
            };
            assert_eq!(files[0].file_name().unwrap(), "temporary.png");
            assert_eq!(fs::read(&files[0]).unwrap(), png);
            // SAFETY: only the private pasteboard created above is released.
            let _: () = unsafe { objc2::msg_send![&*board, releaseGlobally] };
        });
    }

    /// Exercises the plugin backend without inspecting or replacing a user's general clipboard.
    #[test]
    #[ignore = "requires the macOS pasteboard service"]
    fn private_pasteboard_orders_files_and_excludes_own_or_concealed_copies() {
        autoreleasepool(|_| {
            let board = NSPasteboard::pasteboardWithUniqueName();
            let paths = vec![
                std::path::PathBuf::from("/tmp/一 图.png"),
                "/tmp/二.jpg".into(),
            ];
            publish(&board, &Payload::Files(paths.clone())).unwrap();
            assert!(read(&board).unwrap().is_none());
            let actual = board
                .pasteboardItems()
                .unwrap()
                .iter()
                .map(|i| {
                    Url::parse(
                        &i.stringForType(&NSString::from_str(FILE))
                            .unwrap()
                            .to_string(),
                    )
                    .unwrap()
                    .to_file_path()
                    .unwrap()
                })
                .collect::<Vec<_>>();
            assert_eq!(actual, paths);
            let items = paths
                .iter()
                .map(|p| {
                    let item = NSPasteboardItem::new();
                    assert!(item.setString_forType(
                        &NSString::from_str(Url::from_file_path(p).unwrap().as_str()),
                        &NSString::from_str(FILE)
                    ));
                    ProtocolObject::from_retained(item)
                })
                .collect::<Vec<_>>();
            board.clearContents();
            assert!(board.writeObjects(&NSArray::from_retained_slice(&items)));
            assert_eq!(read(&board).unwrap().unwrap().len(), 2);
            board.clearContents();
            board.setString_forType(&NSString::from_str("private"), &NSString::from_str(TEXT));
            board.setString_forType(
                &NSString::from_str("1"),
                &NSString::from_str("org.nspasteboard.ConcealedType"),
            );
            assert!(read(&board).unwrap().is_none());
            let text = NSPasteboardItem::new();
            assert!(
                text.setString_forType(&NSString::from_str("visible"), &NSString::from_str(TEXT))
            );
            let hidden = NSPasteboardItem::new();
            assert!(hidden.setString_forType(
                &NSString::from_str("1"),
                &NSString::from_str("org.nspasteboard.ConcealedType")
            ));
            board.clearContents();
            assert!(board.writeObjects(&NSArray::from_retained_slice(&[
                ProtocolObject::from_retained(text),
                ProtocolObject::from_retained(hidden),
            ])));
            assert!(read(&board).unwrap().is_none());
            // SAFETY: releaseGlobally removes this uniquely named test pasteboard from the server.
            let _: () = unsafe { objc2::msg_send![&*board, releaseGlobally] };
        });
    }

    /// Drives the resident listener, SQLite and the native publisher together on an isolated board.
    #[test]
    #[ignore = "requires the macOS pasteboard service"]
    fn private_pasteboard_restores_a_deleted_image_group_without_a_window() {
        autoreleasepool(|_| {
            let board = NSPasteboard::pasteboardWithUniqueName();
            let name = board.name().to_string();
            board.clearContents();
            assert!(board.setString_forType(
                &NSString::from_str("before opt-in"),
                &NSString::from_str(TEXT)
            ));
            let temp = tempfile::tempdir().unwrap();
            let root = temp.path().join("history");
            let (events, mut rx) = futures::channel::mpsc::unbounded();
            let core = Arc::new(Core::new(History::new(root.clone()), events));
            let run = Monitor::start(Arc::clone(&core), 1, move |run| {
                watch_board(
                    &NSPasteboard::pasteboardWithName(&NSString::from_str(&name)),
                    run,
                )
            })
            .unwrap();
            let mut wait = |ready: bool| {
                let until = Instant::now() + Duration::from_secs(5);
                loop {
                    match rx.try_recv() {
                        Ok(Notice::Status(_, "clipboard.recording")) if ready => break,
                        Ok(Notice::Saved(_)) if !ready => break,
                        Ok(Notice::Status(_, other)) => assert_eq!(other, "clipboard.recording"),
                        _ => {}
                    }
                    assert!(
                        Instant::now() < until,
                        "native monitor did not deliver its update"
                    );
                    thread::sleep(Duration::from_millis(10));
                }
            };
            wait(true);
            let one = include_bytes!("../../../../../../assets/icons/rtools-22.png").as_slice();
            let two = include_bytes!("../../../../../../assets/icons/rtools-44.png").as_slice();
            let paths = [
                temp.path().join("first.png"),
                temp.path().join("第二张.png"),
            ];
            let mut items = Vec::new();
            for (path, data) in paths.iter().zip([one, two]) {
                fs::write(path, data).unwrap();
                let item = NSPasteboardItem::new();
                assert!(item.setString_forType(
                    &NSString::from_str(Url::from_file_path(path).unwrap().as_str()),
                    &NSString::from_str(FILE)
                ));
                items.push(ProtocolObject::from_retained(item));
            }
            board.clearContents();
            assert!(board.writeObjects(&NSArray::from_retained_slice(&items)));
            wait(false);
            for path in paths {
                fs::remove_file(path).unwrap();
            }
            let reopened = History::new(root);
            assert_eq!(reopened.search("", false).unwrap().len(), 1);
            let id = reopened.search("第二张", true).unwrap()[0].id;
            let group = reopened.prepare(id, Selection::All, None).unwrap();
            publish(&board, &group.payload).unwrap();
            assert!(read(&board).unwrap().is_none());
            let copied = board
                .pasteboardItems()
                .unwrap()
                .iter()
                .map(|item| {
                    let uri = item
                        .stringForType(&NSString::from_str(FILE))
                        .unwrap()
                        .to_string();
                    fs::read(Url::parse(&uri).unwrap().to_file_path().unwrap()).unwrap()
                })
                .collect::<Vec<_>>();
            assert_eq!(copied, [one, two]);
            publish(
                &board,
                &reopened
                    .prepare(id, Selection::One(1), None)
                    .unwrap()
                    .payload,
            )
            .unwrap();
            assert_eq!(
                board
                    .dataForType(&NSString::from_str("public.png"))
                    .unwrap()
                    .to_vec(),
                two
            );

            // A genuine multi-image copy immediately after replay must still be captured once.
            let items =
                [two, one].map(|data| {
                    let item = NSPasteboardItem::new();
                    assert!(item.setData_forType(
                        &NSData::with_bytes(data),
                        &NSString::from_str("public.png")
                    ));
                    assert!(item.setString_forType(
                        &NSString::from_str("image alias"),
                        &NSString::from_str(TEXT)
                    ));
                    ProtocolObject::from_retained(item)
                });
            board.clearContents();
            assert!(board.writeObjects(&NSArray::from_retained_slice(&items)));
            wait(false);
            let rows = reopened.search("", false).unwrap();
            assert_eq!(rows.len(), 2);
            assert_eq!((rows[0].images, rows[0].total), (2, 2));
            for raster in [one, two] {
                board.clearContents();
                assert!(board.setData_forType(
                    Some(&NSData::with_bytes(raster)),
                    &NSString::from_str("public.png")
                ));
                wait(false);
            }
            assert_eq!(reopened.search("", true).unwrap().len(), 4);
            run.stop();
            board.clearContents();
            assert!(board.setString_forType(
                &NSString::from_str("after disable"),
                &NSString::from_str(TEXT)
            ));
            thread::sleep(Duration::from_millis(250));
            assert_eq!(reopened.search("", false).unwrap().len(), 4);
            // SAFETY: only the test's unique, private pasteboard is released.
            let _: () = unsafe { objc2::msg_send![&*board, releaseGlobally] };
        });
    }
    /// Re-establishes the native baseline at clear even if the previous offer was never polled.
    #[test]
    #[ignore = "requires the macOS pasteboard service"]
    fn private_pasteboard_clear_excludes_unpolled_copy_and_keeps_the_next_one() {
        autoreleasepool(|_| {
            let board = NSPasteboard::pasteboardWithUniqueName();
            let name = board.name().to_string();
            let temp = tempfile::tempdir().unwrap();
            let (events, mut notices) = futures::channel::mpsc::unbounded();
            let core = Arc::new(Core::new(History::new(temp.path().to_owned()), events));
            core.history.search("", false).unwrap();
            let (reopening, paused) = std::sync::mpsc::channel();
            let (release, resume) = std::sync::mpsc::channel();
            let mut subscriptions = 0;
            let run = Monitor::start(Arc::clone(&core), 1, move |r| {
                subscriptions += 1;
                if subscriptions == 3 {
                    reopening.send(()).unwrap();
                    resume.recv().unwrap();
                }
                watch_board(
                    &NSPasteboard::pasteboardWithName(&NSString::from_str(&name)),
                    r,
                )
            })
            .unwrap();
            let deadline = Instant::now() + Duration::from_secs(5);
            while !matches!(
                notices.try_recv(),
                Ok(Notice::Status(_, "clipboard.recording"))
            ) {
                assert!(Instant::now() < deadline);
                thread::sleep(Duration::from_millis(2));
            }
            board.clearContents();
            assert!(board.setString_forType(
                &NSString::from_str("before clear"),
                &NSString::from_str(TEXT)
            ));
            core.remove(None).unwrap();
            thread::sleep(Duration::from_millis(350));
            assert!(
                core.history.search("", false).unwrap().is_empty(),
                "unpolled copy returned"
            );
            thread::scope(|scope| {
                let clear = scope.spawn(|| core.remove(None));
                paused.recv_timeout(Duration::from_secs(3)).unwrap();
                // A copy made while the new watcher opens must survive the clear boundary too.
                board.clearContents();
                assert!(board.setString_forType(
                    &NSString::from_str("after clear"),
                    &NSString::from_str(TEXT)
                ));
                release.send(()).unwrap();
                clear.join().unwrap().unwrap();
            });
            while core
                .history
                .search("after clear", false)
                .unwrap()
                .is_empty()
            {
                assert!(Instant::now() < deadline, "first post-clear offer was lost");
                thread::sleep(Duration::from_millis(10));
            }
            run.stop();
            // SAFETY: this is the private pasteboard created above.
            let _: () = unsafe { objc2::msg_send![&*board, releaseGlobally] };
        });
    }
